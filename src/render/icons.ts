const hex = (c: string): [number, number, number] => {
  const n = parseInt(c.replace('#', ''), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const mix = (c: string, t: string, k: number) => {
  const a = hex(c), b = hex(t);
  return `rgb(${Math.round(a[0] + (b[0] - a[0]) * k)},${Math.round(a[1] + (b[1] - a[1]) * k)},${Math.round(a[2] + (b[2] - a[2]) * k)})`;
};

const cache = new Map<string, HTMLCanvasElement>();
/** Ícone 32x32 (8x8 ampliado 3x + moldura). */
export function iconCanvas(key: IconKey, col: string): HTMLCanvasElement {
  const id = key + col;
  const hit = cache.get(id); if (hit) return hit;
  const c = document.createElement('canvas'); c.width = c.height = 32;
  const g = c.getContext('2d')!;
  const grad = g.createLinearGradient(0, 0, 0, 32);
  grad.addColorStop(0, mix(col, '#000000', 0.78)); grad.addColorStop(1, mix(col, '#000000', 0.9));
  g.fillStyle = grad; g.fillRect(0, 0, 32, 32);
  g.strokeStyle = mix(col, '#000000', 0.35); g.lineWidth = 2; g.strokeRect(1, 1, 30, 30);
  const pal: Record<string, string> = { '1': col, '2': mix(col, '#ffffff', 0.6), '0': mix(col, '#000000', 0.5) };
  BM[key].forEach((row, y) => [...row].forEach((ch, x) => { if (pal[ch]) { g.fillStyle = pal[ch]; g.fillRect(4 + x * 3, 4 + y * 3, 3, 3); } }));
  cache.set(id, c);
  return c;
}
const urls = new Map<string, string>();
export function iconURL(key: IconKey, col: string): string {
  const id = key + col; let u = urls.get(id);
  if (!u) { u = iconCanvas(key, col).toDataURL(); urls.set(id, u); }
  return u;
}
